//! Syntax highlighting — the Rust slice of `highlightCode` /
//! `getLanguageFromPath` / `supportsLanguage`
//! (`packages/coding-agent/src/modes/interactive/theme/theme.ts:1160-1250` and
//! `packages/coding-agent/src/utils/syntax-highlight.ts`) @ pi 0.82.1 (2efa728).
//!
//! Upstream highlights with highlight.js 10.7.3 through a self-written
//! HTML→ANSI renderer; rpi uses syntect (Sublime Text grammars) per
//! ADR-0008 / D-051, so the ANSI token boundaries differ from upstream while
//! the scope→color mapping is anchored to the same `buildCliHighlightTheme`
//! theme keys (theme.ts:1118-1146) — same color family for the same token
//! kind.
//!
//! Intentional differences:
//! - The embedded syntax set is bat's curated set (generated by `build.rs`
//!   from `syntect-assets`), not syntect's built-in defaults — the latter
//!   lack TypeScript/TOML/Dockerfile/… as of syntect 5.3. Six grammars whose
//!   regexes the pure-Rust fancy-regex backend cannot compile are excluded
//!   (see [`FANCY_INCOMPATIBLE`]); of the 43 languages reachable through
//!   [`get_language_from_path`], only `powershell` is affected and falls back
//!   to the plain `mdCodeBlock` color like any unsupported language.
//! - `supportsLanguage` (hljs `getLanguage` name/alias lookup) becomes
//!   "resolvable in the embedded syntect syntax set by name or alias,
//!   case-insensitive".
//! - Scope matching mirrors the upstream formatter resolution order
//!   (exact → dot prefix → dash prefix, innermost span first,
//!   syntax-highlight.ts:33-70) via an ordered prefix table — see
//!   [`SCOPE_STYLES`].

