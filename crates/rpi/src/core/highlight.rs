/// zlib-compressed bincode dump of the syntax set, written by `build.rs`
/// into `OUT_DIR` (bat's curated set, fancy-regex verified).
static SYNTAX_SET: OnceLock<Result<SyntaxSet, String>> = OnceLock::new();

fn syntax_set() -> Option<&'static SyntaxSet> {
    SYNTAX_SET
        .get_or_init(|| {
            let dump: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/syntaxes.bin"));
            syntect::dumps::from_reader(dump).map_err(|e| format!("load embedded syntax dump: {e}"))
        })
        .as_ref()
        .ok()
}

