    /// Strip SGR sequences — test-only approximation of terminal display.
    fn strip_ansi(s: &str) -> String {
        let mut out = String::with_capacity(s.len());
        let mut rest = s;
        while let Some(idx) = rest.find('\x1b') {
            out.push_str(&rest[..idx]);
            let tail = &rest[idx..];
            if tail.as_bytes().get(1) != Some(&b'[') {
                out.push_str(tail);
                return out;
            }
            match tail.find('m') {
                Some(end) => rest = &tail[end + 1..],
                None => {
                    out.push_str(tail);
                    return out;
                }
            }
        }
        out.push_str(rest);
        out
    }

