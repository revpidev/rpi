/// Resolve a language name to a syntax reference: exact name, then
/// case-insensitive name scan, then the redirect/alias tables (hljs
/// `getLanguage` semantics, syntax-highlight.ts:144-146). Excluded syntaxes
/// never resolve.
fn find_syntax(name: &str) -> Option<&'static SyntaxReference> {
    let set = syntax_set()?;
    let target = CANONICAL_NAME_REDIRECTS
        .iter()
        .chain(LANGUAGE_ALIASES)
        .find(|(alias, _)| alias.eq_ignore_ascii_case(name))
        .map(|(_, syntax_name)| *syntax_name)
        .unwrap_or(name);
    let syntax = set.find_syntax_by_name(target).or_else(|| {
        set.syntaxes()
            .iter()
            .find(|s| s.name.eq_ignore_ascii_case(target))
    })?;
    if FANCY_INCOMPATIBLE.contains(&syntax.name.as_str()) {
        return None;
    }
    Some(syntax)
}

/// `supportsLanguage` (theme.ts:1161-1162): whether a language name can be
/// highlighted. hljs resolves names and aliases case-insensitively; syntect
/// syntax names are title-case, so the check is case-insensitive.
pub fn supports_language(name: &str) -> bool {
    find_syntax(name).is_some()
}

