    // --- scope mapping color families ----------------------------------------

    #[test]
    fn rust_tokens_use_distinct_color_families() {
        let t = theme();
        let code = "fn main() {\n    if x == 1 {\n        let s = \"hi\"; // note\n    }\n}\n";
        let lines = highlight_code(code, Some("rust"), &t);
        let out = lines.join("\n");
        let keyword = t.get_fg_ansi("syntaxKeyword");
        let string = t.get_fg_ansi("syntaxString");
        let comment = t.get_fg_ansi("syntaxComment");
        let number = t.get_fg_ansi("syntaxNumber");
        // The three families must be colored differently from each other.
        assert_ne!(keyword, string);
        assert_ne!(keyword, comment);
        assert_ne!(string, comment);
        assert!(out.contains(keyword), "keywords must use syntaxKeyword");
        assert!(out.contains(string), "strings must use syntaxString");
        assert!(out.contains(comment), "comments must use syntaxComment");
        assert!(out.contains(number), "numbers must use syntaxNumber");
        // `fn`/`let` are storage.type in the Rust grammar → syntaxType;
        // `main` is entity.name.function → syntaxFunction.
        assert!(out.contains(t.get_fg_ansi("syntaxType")));
        assert!(out.contains(t.get_fg_ansi("syntaxFunction")));
    }

    // --- highlightCode round-trip --------------------------------------------

    #[test]
    fn highlight_code_emits_ansi_and_strips_back_to_original() {
        let t = theme();
        let code = "fn main() {\n    let x = 1; // comment\n    println!(\"hi\");\n}\n";
        let lines = highlight_code(code, Some("rust"), &t);
        assert_eq!(lines.len(), 5, "trailing newline keeps the empty line");
        for (i, line) in lines.iter().enumerate() {
            let expected = code.split('\n').nth(i).unwrap_or("");
            if expected.is_empty() {
                // Trailing empty element of the upstream split — no text, no
                // color codes.
                assert_eq!(line, "");
                continue;
            }
            assert!(
                line.contains('\x1b'),
                "line {i} must carry ANSI color codes"
            );
            let stripped = strip_ansi(line);
            assert_eq!(stripped, expected, "line {i} must round-trip");
        }
    }

    #[test]
    fn alias_languages_highlight() {
        let t = theme();
        let cases: [(&str, &str, &[&str]); 3] = [
            (
                "csharp",
                "class Foo {\n    string s = \"x\";\n}\n",
                &["syntaxType", "syntaxString", "syntaxVariable"],
            ),
            (
                "protobuf",
                "message Foo {\n    string bar = 1;\n}\n",
                &["syntaxType", "syntaxVariable"],
            ),
            (
                "hcl",
                "resource \"a\" \"b\" {\n    c = 1\n}\n",
                &["syntaxString", "syntaxVariable"],
            ),
        ];
        for (lang, code, needles) in cases {
            let lines = highlight_code(code, Some(lang), &t);
            let out = lines.join("\n");
            assert!(out.contains('\x1b'), "{lang} must produce ANSI colors");
            for needle in needles {
                assert!(
                    out.contains(t.get_fg_ansi(needle)),
                    "{lang} must produce {needle} colors"
                );
            }
            // Round-trip: stripped output equals the input, split by line.
            let stripped: Vec<String> = lines.iter().map(|l| strip_ansi(l)).collect();
            let expected: Vec<String> = code.split('\n').map(str::to_string).collect();
            assert_eq!(stripped, expected, "{lang} must round-trip");
        }
    }
