/// Highlight `code` in the given language, returning one styled line per
/// line of input (the same shape as upstream `highlight(code, opts).split(
/// "\n")`).
///
/// Fallbacks, mirroring theme.ts:1160-1179: an invalid/unknown language (or
/// `None`) colors each line with `mdCodeBlock` (upstream deliberately skips
/// hljs auto-detection, which misidentifies prose); any syntect error — and
/// any panic from a grammar the fancy-regex backend cannot compile, which the
/// embedded set is verified against at build time — returns the plain
/// uncolored lines (upstream's `try/catch`, theme.ts:1174-1178).
pub fn highlight_code(code: &str, lang: Option<&str>, theme: &Theme) -> Vec<String> {
    // `validLang = lang && supportsLanguage(lang) ? lang : undefined`
    // (theme.ts:1161-1162).
    let Some(lang) = lang.filter(|l| supports_language(l)) else {
        return code
            .split('\n')
            .map(|line| theme.fg("mdCodeBlock", line))
            .collect();
    };
    let Some(syntax) = find_syntax(lang) else {
        return code
            .split('\n')
            .map(|line| theme.fg("mdCodeBlock", line))
            .collect();
    };
    if code.is_empty() {
        // Upstream: `"".split("\n")` yields one empty line.
        return vec![String::new()];
    }
    match std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        highlight_lines(code, syntax, theme)
    })) {
        Ok(Ok(lines)) => lines,
        Ok(Err(_)) | Err(_) => code.split('\n').map(str::to_string).collect(),
    }
}

fn highlight_lines(
    code: &str,
    syntax: &'static SyntaxReference,
    theme: &Theme,
) -> Result<Vec<String>, String> {
    let Some(set) = syntax_set() else {
        return Err("embedded syntax set unavailable".to_string());
    };
    let mut parse_state = ParseState::new(syntax);
    // Scope stack is advanced by the ops `parse_line` returns, exactly like
    // syntect's `HighlightState` does (highlighting/highlighter.rs).
    let mut stack = ScopeStack::new();
    let mut lines: Vec<String> = Vec::new();
    for chunk in LinesWithEndings::from(code) {
        // Parse in newlines mode (grammars are line-aware); render without the
        // trailing newline — the returned lines are upstream's
        // `highlight(code, opts).split("\n")` elements (theme.ts:1175), which
        // the markdown renderer pushes as whole lines.
        let content = chunk.strip_suffix('\n').unwrap_or(chunk);
        let ops = parse_state
            .parse_line(chunk, set)
            .map_err(|e| e.to_string())?;
        let mut rendered = String::with_capacity(content.len() * 2);
        let mut pos = 0usize;
        for (end, op) in ops {
            // Ops may reference the newline position past the content.
            let end = end.min(content.len());
            let snapshot = stack.clone();
            rendered.push_str(&render_range(&content[pos..end], &snapshot, theme));
            stack.apply(&op).map_err(|e| e.to_string())?;
            pos = end;
        }
        if pos < content.len() {
            rendered.push_str(&render_range(&content[pos..], &stack, theme));
        }
        lines.push(rendered);
    }
    if code.ends_with('\n') {
        // Upstream `split("\n")` keeps the trailing empty element.
        lines.push(String::new());
    }
    Ok(lines)
}

