/// A style operation on a text run — either a theme foreground color or one
/// of the raw chalk-style helpers (bold/italic/underline, theme.ts:1140-1142).
#[derive(Clone, Copy, PartialEq, Eq)]
enum Style {
    Fg(&'static str),
    Bold,
    Italic,
    Underline,
}

/// Ordered scope-prefix table mirroring `buildCliHighlightTheme`'s hljs class
/// families. Matching is prefix-based (`scope == prefix` or
/// `scope.starts_with(prefix + ".")`), which corresponds to upstream's
/// `exact → dot prefix → dash prefix` resolution (syntax-highlight.ts:33-56;
/// TextMate scopes contain no dashes, so the dash rule never fires here), and
/// the table order encodes specificity — `keyword.operator` wins over
/// `keyword`, and `meta` (the whole-construct wrapper) is the last fallback
/// tier, matching upstream's `meta → muted` mapping. Unmatched scopes stay
/// uncolored. hljs classes upstream also maps (built_in/class/type/title/tag/
/// name/attr/params/doctag/literal/emphasis/strong/link/addition/deletion)
/// are covered by these syntect scope families: built_in→support.*, class/
/// title→entity.name.*, type→storage.type, tag→meta.tag (muted wrapper),
/// name→entity.name.*, attr/params→variable.*, doctag→comment.*, literal→
/// constant.language, emphasis/strong/link→markup.italic/bold/underline.link,
/// addition/deletion→markup.inserted/deleted.
const SCOPE_STYLES: &[(&str, Style)] = &[
    ("keyword.operator", Style::Fg("syntaxOperator")),
    ("keyword", Style::Fg("syntaxKeyword")),
    ("comment", Style::Fg("syntaxComment")),
    ("string", Style::Fg("syntaxString")),
    ("constant.numeric", Style::Fg("syntaxNumber")),
    ("constant.language", Style::Fg("syntaxNumber")),
    ("entity.name.function", Style::Fg("syntaxFunction")),
    // Class declaration names: upstream hljs emits the `title` class for them
    // (`title` → syntaxFunction, theme.ts:1130).
    ("entity.name.class", Style::Fg("syntaxFunction")),
    ("support.function", Style::Fg("syntaxFunction")),
    ("entity.name.type", Style::Fg("syntaxType")),
    ("storage.type", Style::Fg("syntaxType")),
    ("support.type", Style::Fg("syntaxType")),
    ("variable", Style::Fg("syntaxVariable")),
    ("support.constant", Style::Fg("syntaxVariable")),
    ("punctuation", Style::Fg("syntaxPunctuation")),
    ("markup.underline.link", Style::Underline),
    ("markup.bold", Style::Bold),
    ("markup.italic", Style::Italic),
    ("markup.inserted", Style::Fg("toolDiffAdded")),
    ("markup.deleted", Style::Fg("toolDiffRemoved")),
    // NOTE: upstream maps the hljs `meta` class to `muted` (theme.ts:1128),
    // but syntect `meta.*` scopes wrap ordinary code everywhere (function and
    // block bodies), so a `meta → muted` fallback would render plain text
    // grey. Unmatched scopes stay uncolored, matching upstream's "no class →
    // no styling" look (ADR-0008 visual-intent alignment).
];

fn style_for_scope(scope: &str) -> Option<Style> {
    SCOPE_STYLES.iter().find_map(|(prefix, style)| {
        let matched = scope == *prefix
            || scope
                .strip_prefix(prefix)
                .is_some_and(|rest| rest.starts_with('.'));
        matched.then_some(*style)
    })
}

/// Apply the innermost matching style, walking the stack from the top —
/// upstream `getActiveFormatter` iterates the hljs span classes innermost
/// first (syntax-highlight.ts:58-70).
fn render_range(text: &str, stack: &ScopeStack, theme: &Theme) -> String {
    if text.is_empty() {
        return String::new();
    }
    let Some(style) = stack
        .as_slice()
        .iter()
        .rev()
        .find_map(|scope| style_for_scope(&scope.to_string()))
    else {
        return text.to_string();
    };
    match style {
        Style::Fg(color) => theme.fg(color, text),
        Style::Bold => Theme::bold(text),
        Style::Italic => Theme::italic(text),
        Style::Underline => Theme::underline(text),
    }
}

