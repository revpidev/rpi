//! Session entry serde skeleton (T01; behavior lands in T07/T16).
//!
//! Consolidates the entry types of
//! `packages/coding-agent/src/core/session-manager.ts` and
//! `packages/agent/src/harness/types.ts` @ pi 0.82.1 (2efa728) into a single
//! source shared by the `pir` main path and the `pir-agent` harness layer.
//!
//! Intentional differences (structural, wire-compatible):
//! - Upstream defines two near-identical entry type families (coding-agent
//!   `SessionEntry`, harness `SessionTreeEntry`). Rust has no structural
//!   typing, so both are unified here: one payload struct per entry type, one
//!   [`SessionEntry`] enum with all 11 variants (9 main-path +
//!   harness-only `active_tools_change` / `leaf`), plus [`SessionHeader`] and
//!   the [`FileEntry`] raw file union (requirements §6.2).
//! - `CompactionEntry` supports both persisted forms: the main-path
//!   `firstKeptEntryId` form and the harness self-contained `retainedTail`
//!   form (both fields optional on the type; ADR-0003 §1). Write discipline is
//!   enforced by the writers, not the type: the `pir` main path writes only
//!   `firstKeptEntryId` (pinned-version behavior); the harness may write
//!   either form.
//!
//! Field nullability mirrors upstream exactly: `parentId` / `leaf.targetId`
//! are `string | null` (always serialized, `null` when absent); fields typed
//! `... | undefined` upstream are omitted from JSON when `None`.

use pir_ai::types::Usage;
