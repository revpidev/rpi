    #[test]
    fn session_header_shape() {
        let header = SessionHeader {
            version: Some(CURRENT_SESSION_VERSION),
            id: "s1".to_owned(),
            timestamp: "2026-07-30T00:00:00.000Z".to_owned(),
            cwd: "/repo".to_owned(),
            parent_session: None,
        };
        let entry = FileEntry::Session(header.clone());
        assert_eq!(
            to_json(&entry),
            r#"{"type":"session","version":3,"id":"s1","timestamp":"2026-07-30T00:00:00.000Z","cwd":"/repo"}"#
        );
        let back: FileEntry = serde_json::from_str(&to_json(&entry)).expect("roundtrip");
        assert_eq!(back, entry);

        // v1 sessions have no `version` key; `parentSession` appears when set.
        let v1 = SessionHeader {
            version: None,
            parent_session: Some("parent".to_owned()),
            ..header
        };
        let v: Value = serde_json::from_str(&to_json(&FileEntry::Session(v1))).expect("parse");
        assert!(v.get("version").is_none());
        assert_eq!(v["parentSession"], json!("parent"));
    }

